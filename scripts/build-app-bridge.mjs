#!/usr/bin/env node

/**
 * build-app-bridge.mjs
 *
 * Rebuilds `packages/pi-mcp/lib/_app-bridge.bundle.js` from the dependency it
 * belongs to.
 *
 * The file is a browser bundle of `@modelcontextprotocol/ext-apps/app-bridge`.
 * It has to exist because the package entry is not servable to a browser as
 * published: `app-bridge.js` imports `@modelcontextprotocol/client`,
 * `@modelcontextprotocol/core` and `zod/v4` by bare specifier, and a browser
 * cannot resolve those. pi-mcp serves the bundle over its local UI server, so
 * the imports must be inlined first.
 *
 * The output is deterministic for a given dependency version, which is what lets
 * test/app-bridge-bundle.test.mjs rebuild it and compare bytes.
 *
 * Usage:
 *   node scripts/build-app-bridge.mjs
 */

import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PACKAGE_DIR = join(ROOT, 'packages', 'pi-mcp');
/**
 * Where the generated bundle is written, and what the freshness test reads.
 *
 * @type {string}
 */
export const OUTPUT_FILE = join(PACKAGE_DIR, 'lib', '_app-bridge.bundle.js');

/** The entry point the host HTML imports from, as a bare specifier. */
const ENTRY = '@modelcontextprotocol/ext-apps/app-bridge';

/**
 * Bundle the app bridge for the browser.
 *
 * `absWorkingDir` is the package directory rather than the repository root, so
 * the dependency resolves the way the published package will resolve it.
 *
 * @returns {Promise<string>} the bundled source
 */
export async function buildAppBridge() {
  const result = await build({
    absWorkingDir: PACKAGE_DIR,
    bundle: true,
    entryPoints: [ENTRY],
    format: 'esm',
    legalComments: 'none',
    minify: true,
    platform: 'browser',
    target: 'es2022',
    write: false,
  });

  return result.outputFiles[0].text;
}

/**
 * The dependency version the bundle was built from. Recorded in a header so a
 * reader of the committed file can tell what it contains without rebuilding it.
 *
 * @returns {string}
 */
export function appBridgeVersion() {
  const manifest = JSON.parse(readFileSync(join(PACKAGE_DIR, 'package.json'), 'utf8'));

  return manifest.dependencies['@modelcontextprotocol/ext-apps'];
}

/**
 * The exact bytes the committed file should contain: a provenance header plus
 * the bundle. One function so the writer and the freshness test cannot disagree
 * about what "up to date" means.
 *
 * @returns {Promise<string>}
 */
export async function buildAppBridgeSource() {
  const bundled = await buildAppBridge();
  const header = `// Generated by scripts/build-app-bridge.mjs from ${ENTRY} in @modelcontextprotocol/ext-apps ${appBridgeVersion()}.\n// Do not edit by hand: run \`pnpm build:app-bridge\` instead.\n`;

  return header + bundled;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { writeFileSync } = await import('node:fs');
  const source = await buildAppBridgeSource();

  writeFileSync(OUTPUT_FILE, source);
  console.log(`wrote ${OUTPUT_FILE} (${source.length} bytes)`);
}
